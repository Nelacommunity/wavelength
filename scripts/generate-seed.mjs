// Generates supabase/seed.sql from data/catalog.json.
// Usage: node scripts/generate-seed.mjs
//
// Everything this produces is DEMO data: demo users cannot sign in (random
// passwords), and every stats row is tagged source = 'demo'.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(join(root, "data/catalog.json"), "utf8"));

// Deterministic PRNG so the seed is stable across runs.
let state = 20261017;
const rand = () => {
  state = (state * 1664525 + 1013904223) % 4294967296;
  return state / 4294967296;
};
const pick = (arr) => arr[Math.floor(rand() * arr.length)];
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const uid = (n) => `00000000-0000-4000-8000-${String(n).padStart(12, "0")}`;

const users = [
  ["mira_waves", "Mira Okafor", "Afrobeats evangelist. Lagos → London. Always one tune ahead.", "NG"],
  ["jonas.k", "Jonas Keller", "Techno at night, jazz in the morning.", "DE"],
  ["lucia_sounds", "Lucía Fernández", "Reggaetón, boleros y todo lo demás.", "MX"],
  ["dev_beats", "Dev Raman", "Bedroom producer. Sharing what's on repeat.", "IN"],
  ["hana_moon", "Hana Moon", "K-pop & city pop collector 🌙", "KR"],
  ["sam_rivers", "Sam Rivers", "Indie kid forever. Vinyl > everything.", "US"],
  ["ana_br", "Ana Beatriz", "Música brasileira e pop global.", "BR"],
  ["theo_fm", "Theo Martin", "Radio host by day. Crate digger by night.", "FR"],
  ["yuki_loops", "Yuki Tanaka", "Loops, lo-fi and late trains.", "JP"],
  ["olivia_hz", "Olivia Hart", "Pop girlie with a rock heart.", "GB"],
].map(([username, name, bio, country], i) => ({ id: uid(i + 1), username, name, bio, country }));

const captions = [
  "This has been on repeat all week. The production is unreal.",
  "Late night drive song. Windows down, volume up.",
  "Can't believe I slept on this one for so long.",
  "The bridge on this track 🤯",
  "Perfect for a rainy Sunday.",
  "If you only listen to one thing today, make it this.",
  "Throwback that still hits every single time.",
  "My gym playlist just got a new #1.",
  "Who else is obsessed with this right now?",
  "Found this through a friend and now I can't stop.",
  "Pure serotonin in song form.",
  "Headphones on, world off.",
  "This chorus lives in my head rent free.",
  "Instant classic. Calling it now.",
  "",
];
const comments = [
  "Absolute banger 🔥", "Been looping this all day", "The production on this!!",
  "Adding to my favorites right now", "Such a vibe", "Thanks for sharing, new to me",
  "This takes me back", "Underrated for sure", "Need the full album now", "Chills every time",
];
const reactions = ["fire", "heart", "headphones", "dance", "chills"];

// Per-song trend shape: popularity, long-run slope, and a recent breakout bump.
const rising = new Set(["Doechii", "ROSÉ & Bruno Mars", "Tyla", "Laufey", "Bad Bunny", "Sabrina Carpenter"]);
const falling = new Set(["Daft Punk", "Disclosure & Sam Smith", "Fleetwood Mac", "Rema & Selena Gomez", "NewJeans"]);
const breakout = new Set(["Doechii", "Tems", "Peggy Gou"]);
const params = catalog.map((s) => {
  const pop = 0.35 + rand() * 0.65;
  let slope = (rand() - 0.5) * 0.4;
  if (rising.has(s.artist)) slope = 0.5 + rand() * 0.4;
  if (falling.has(s.artist)) slope = -0.35 - rand() * 0.25;
  const bump = breakout.has(s.artist) ? 1.2 + rand() * 0.8 : 0;
  return { provider_id: s.provider_id, pop: pop.toFixed(3), slope: slope.toFixed(3), bump: bump.toFixed(3) };
});

const out = [];
out.push(`-- GENERATED by scripts/generate-seed.mjs — do not edit by hand.
-- DEMO DATA ONLY. Do not run against a production database.
-- Demo users get random passwords and cannot sign in.
`);

// Songs
out.push("insert into public.songs (provider, provider_id, title, artist, album, artwork_url, preview_url, external_url, genre, duration_ms, release_date) values");
out.push(
  catalog
    .map(
      (s) =>
        `  ('itunes', ${q(s.provider_id)}, ${q(s.title)}, ${q(s.artist)}, ${q(s.album)}, ${q(s.artwork_url)}, ${q(s.preview_url)}, ${q(s.external_url)}, ${q(s.genre)}, ${s.duration_ms ?? "null"}, ${q(s.release_date)})`,
    )
    .join(",\n") + "\non conflict (provider, provider_id) do nothing;\n",
);

// Demo users (auth.users → trigger creates profiles)
out.push(`insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change_token_new, email_change) values`);
out.push(
  users
    .map(
      (u, i) =>
        `  ('00000000-0000-0000-0000-000000000000', '${u.id}', 'authenticated', 'authenticated', '${u.username.replace(".", "_")}@demo.wavelength.invalid',
   extensions.crypt(gen_random_uuid()::text, extensions.gen_salt('bf')), now(),
   '{"provider":"email","providers":["email"],"demo":true}', '{"username":"${u.username.replace(".", "_")}","display_name":${JSON.stringify(u.name).replace(/'/g, "''")}}',
   now() - interval '${120 - i * 7} days', now(), '', '', '', '')`,
    )
    .join(",\n") + "\non conflict (id) do nothing;\n",
);
out.push(
  users
    .map((u) => `update public.profiles set bio = ${q(u.bio)}, country = '${u.country}' where id = '${u.id}';`)
    .join("\n") + "\n",
);

// Follows
const follows = new Set();
for (const a of users) {
  const n = 3 + Math.floor(rand() * 5);
  for (let k = 0; k < n; k++) {
    const b = pick(users);
    if (b.id !== a.id) follows.add(`('${a.id}', '${b.id}')`);
  }
}
out.push(`insert into public.follows (follower_id, following_id) values\n  ${[...follows].join(",\n  ")}\non conflict do nothing;\n`);

// Favorites
const favs = new Set();
for (const u of users) {
  for (let k = 0; k < 6; k++) favs.add(`('${u.id}', '${pick(catalog).provider_id}')`);
}
out.push(`insert into public.favorites (user_id, song_id)
select v.user_id::uuid, s.id from (values
  ${[...favs].join(",\n  ")}
) as v(user_id, provider_id) join public.songs s on s.provider = 'itunes' and s.provider_id = v.provider_id
on conflict do nothing;
`);

// Posts, likes, comments, reactions
const posts = [];
for (let i = 0; i < 32; i++) {
  posts.push({
    id: `10000000-0000-4000-8000-${String(i + 1).padStart(12, "0")}`,
    user: pick(users),
    song: pick(catalog),
    caption: pick(captions),
    minutesAgo: Math.floor(i * 290 + rand() * 200),
  });
}
out.push(`insert into public.music_posts (id, user_id, song_id, caption, created_at)
select v.id::uuid, v.user_id::uuid, s.id, v.caption, now() - (v.minutes_ago || ' minutes')::interval from (values
  ${posts.map((p) => `('${p.id}', '${p.user.id}', ${q(p.song.provider_id)}, ${q(p.caption)}, ${p.minutesAgo})`).join(",\n  ")}
) as v(id, user_id, provider_id, caption, minutes_ago) join public.songs s on s.provider = 'itunes' and s.provider_id = v.provider_id
on conflict do nothing;
`);

const likes = new Set();
const reacts = new Set();
const commentRows = [];
for (const p of posts) {
  for (const u of users) {
    if (u.id === p.user.id) continue;
    const r = rand();
    if (r < 0.45) likes.add(`('${u.id}', '${p.id}', ${p.minutesAgo})`);
    if (r < 0.2) reacts.add(`('${u.id}', '${p.id}', '${pick(reactions)}', ${p.minutesAgo})`);
    if (r > 0.88) commentRows.push(`('${u.id}', '${p.id}', ${q(pick(comments))}, ${p.minutesAgo})`);
  }
}
out.push(`insert into public.likes (user_id, post_id, created_at)
select v.u::uuid, v.p::uuid, now() - ((v.m - 5) || ' minutes')::interval from (values
  ${[...likes].join(",\n  ")}
) as v(u, p, m) on conflict do nothing;
`);
out.push(`insert into public.post_reactions (user_id, post_id, emoji, created_at)
select v.u::uuid, v.p::uuid, v.e, now() - ((v.m - 7) || ' minutes')::interval from (values
  ${[...reacts].join(",\n  ")}
) as v(u, p, e, m) on conflict do nothing;
`);
out.push(`insert into public.comments (user_id, post_id, body, created_at)
select v.u::uuid, v.p::uuid, v.b, now() - ((v.m - 10) || ' minutes')::interval from (values
  ${commentRows.join(",\n  ")}
) as v(u, p, b, m);
`);

// Daily song stats: 120 days × 10 countries, shaped per song.
out.push(`-- Simulated listener statistics (source = 'demo').
with params(provider_id, pop, slope, bump) as (values
  ${params.map((p) => `(${q(p.provider_id)}, ${p.pop}, ${p.slope}, ${p.bump})`).join(",\n  ")}
),
countries(country, weight) as (values
  ('US', 1.00), ('GB', 0.45), ('BR', 0.50), ('DE', 0.35), ('NG', 0.30),
  ('IN', 0.55), ('JP', 0.30), ('KR', 0.25), ('MX', 0.40), ('FR', 0.30)
),
affinity(genre, country, boost) as (values
  ('Latin', 'MX', 2.4), ('Latin', 'BR', 1.7), ('Afrobeats', 'NG', 3.2), ('Afrobeats', 'GB', 1.4),
  ('K-Pop', 'KR', 3.2), ('K-Pop', 'JP', 1.9), ('Electronic', 'DE', 1.9), ('Electronic', 'GB', 1.3),
  ('Hip-Hop', 'US', 1.3), ('Rock', 'GB', 1.4), ('Jazz', 'FR', 1.5), ('Jazz', 'JP', 1.4),
  ('Pop', 'US', 1.1), ('Indie', 'GB', 1.3), ('R&B', 'US', 1.2), ('R&B', 'NG', 1.3)
),
days as (select generate_series(0, 119) as d),
base as (
  select
    s.id as song_id,
    (current_date - dd.d) as stat_date,
    c.country,
    2500 * p.pop * c.weight * coalesce(a.boost, 1)
      * greatest(0.08, 1 + p.slope * (((119 - dd.d) / 119.0) - 0.5) * 2)
      * (1 + p.bump * exp(-dd.d / 6.0))
      * (case when extract(dow from current_date - dd.d) in (5, 6) then 1.12 else 1 end)
      * (0.9 + 0.2 * ((abs(hashtext(s.id::text || dd.d || c.country)) % 1000) / 1000.0)) as listeners,
    ((abs(hashtext(c.country || dd.d || s.id::text)) % 1000) / 1000.0) as n2
  from params p
  join public.songs s on s.provider = 'itunes' and s.provider_id = p.provider_id
  cross join countries c
  cross join days dd
  left join affinity a on a.genre = s.genre and a.country = c.country
)
insert into public.daily_song_stats (song_id, stat_date, country, source, unique_listeners, plays, likes, shares)
select song_id, stat_date, country, 'demo',
  round(listeners)::int,
  round(listeners * (1.5 + 0.8 * n2))::int,
  round(listeners * 0.035 * (0.8 + 0.4 * n2))::int,
  round(listeners * 0.006 * (0.7 + 0.6 * n2))::int
from base
on conflict do nothing;

-- Simulated platform-level stats (source = 'demo').
insert into public.daily_platform_stats (stat_date, source, total_listeners, active_listeners, new_listeners, shares)
select
  current_date - d, 'demo',
  round(180000 * exp(ln(420.0 / 180.0) * ((119 - d) / 119.0)))::int,
  round(180000 * exp(ln(420.0 / 180.0) * ((119 - d) / 119.0))
    * (0.30 + 0.04 * sin(d / 3.0)) * (case when extract(dow from current_date - d) in (5, 6) then 1.1 else 1 end))::int,
  round(180000 * exp(ln(420.0 / 180.0) * ((119 - d) / 119.0)) * ln(420.0 / 180.0) / 119.0)::int,
  (select coalesce(sum(shares), 0) from public.daily_song_stats where stat_date = current_date - d and source = 'demo')
from generate_series(0, 119) as d
on conflict do nothing;
`);

writeFileSync(join(root, "supabase/seed.sql"), out.join("\n"));
console.log(`Wrote supabase/seed.sql (${catalog.length} songs, ${users.length} demo users, ${posts.length} posts)`);
